export const COMMAND_SHIM_MARKER = ":: generated by oh-my-cybersecurity Codex installer"

// Generated command shims carry the marker on their second line. Checking only that line keeps a file that
// merely embeds the marker string, such as a standalone omc binary bundling this module, from being
// mistaken for a generated shim.
export function hasCommandShimHeader(content: string): boolean {
  return content.split("\n", 2)[1]?.trimEnd() === COMMAND_SHIM_MARKER
}

export function windowsNodeDiscoveryLines(): string[] {
  return [
    "setlocal EnableExtensions EnableDelayedExpansion",
    'set "OMC_NODE_BINARY="',
    'set "OMC_NODE_REPL_NODE_PATH=%NODE_REPL_NODE_PATH%"',
    'if exist "%CODEX_HOME%\\config.toml" (',
    '  for /f "tokens=1,* delims==" %%A in (\'findstr /R /C:"NODE_REPL_NODE_PATH[ ]*=" "%CODEX_HOME%\\config.toml" 2^>nul\') do (',
    '    set "OMC_NODE_REPL_NODE_PATH=%%B"',
    "  )",
    ")",
    "if defined OMC_NODE_REPL_NODE_PATH (",
    '  set "OMC_NODE_BINARY=!OMC_NODE_REPL_NODE_PATH!"',
    '  for /f "tokens=* delims= " %%N in ("!OMC_NODE_BINARY!") do set "OMC_NODE_BINARY=%%N"',
    `  if "!OMC_NODE_BINARY:~0,1!"=="'" set "OMC_NODE_BINARY=!OMC_NODE_BINARY:~1!"`,
    `  if "!OMC_NODE_BINARY:~-1!"=="'" set "OMC_NODE_BINARY=!OMC_NODE_BINARY:~0,-1!"`,
    // A Windows path cannot contain a double quote, so dropping every one strips TOML's quoting.
    // A quote comparison would need ^" inside this parenthesized block, where cmd rejects it.
    '  set "OMC_NODE_BINARY=!OMC_NODE_BINARY:"=!"',
    '  if defined OMC_NODE_BINARY if not exist "!OMC_NODE_BINARY!" set "OMC_NODE_BINARY="',
    ")",
    'if not defined OMC_NODE_BINARY where node >nul 2>nul && set "OMC_NODE_BINARY=node"',
  ]
}

export function windowsCommandShim(targetPath: string): string {
  return [
    "@echo off",
    COMMAND_SHIM_MARKER,
    'if not defined CODEX_HOME set "CODEX_HOME=%USERPROFILE%\\.codex"',
    ...windowsNodeDiscoveryLines(),
    "if not defined OMC_NODE_BINARY (",
    "  echo omc: no Node runtime was discovered from NODE_REPL_NODE_PATH or PATH; rerun LazyCodex install from Codex Desktop 1>&2",
    "  exit /b 127",
    ")",
    `"%OMC_NODE_BINARY%" "${targetPath}" %*`,
    "exit /b %ERRORLEVEL%",
    "",
  ].join("\r\n")
}
